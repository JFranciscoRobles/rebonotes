export const LOCALES: Record<string, Strings> = { en: EN, es: ES };

/** The strings of a language, Spanish or English; English when it is neither. */
export function stringsFor(locale: string | undefined): Strings {
  return LOCALES[(locale ?? 'en').toLowerCase().split('-')[0]] ?? EN;
}

/** `en` or `es`, from a locale. */
export const languageOf = (locale: string | undefined): 'en' | 'es' => ((locale ?? '').toLowerCase().startsWith('es') ? 'es' : 'en');

export const say = (text: string, values: Record<string, string>): string => text.replace(/\{(\w+)\}/g, (_m, k: string) => values[k] ?? '');
